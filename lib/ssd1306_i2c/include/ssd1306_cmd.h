#ifndef SSD1306_CMD_H
#define SSD1306_CMD_H

#include <stdint.h>

typedef enum {
    /* Fundamental */
    SSD1306_CMD_SET_CONTRAST            = 0x81,
    SSD1306_CMD_DISPLAY_ALL_ON_RESUME   = 0xA4,
    SSD1306_CMD_DISPLAY_ALL_ON          = 0xA5,
    SSD1306_CMD_NORMAL_DISPLAY          = 0xA6,
    SSD1306_CMD_INVERT_DISPLAY          = 0xA7,
    SSD1306_CMD_DISPLAY_OFF             = 0xAE,
    SSD1306_CMD_DISPLAY_ON              = 0xAF,

    /* Scrolling */
    SSD1306_CMD_SCROLL_RIGHT            = 0x26,
    SSD1306_CMD_SCROLL_LEFT             = 0x27,
    SSD1306_CMD_SCROLL_VERT_RIGHT       = 0x29,
    SSD1306_CMD_SCROLL_VERT_LEFT        = 0x2A,
    SSD1306_CMD_DEACTIVATE_SCROLL       = 0x2E,
    SSD1306_CMD_ACTIVATE_SCROLL         = 0x2F,
    SSD1306_CMD_SET_VERT_SCROLL_AREA    = 0xA3,

    /* Addressing */
    SSD1306_CMD_SET_LOW_COL             = 0x00,
    SSD1306_CMD_SET_HIGH_COL            = 0x10,
    SSD1306_CMD_SET_MEM_ADDR_MODE       = 0x20,
    SSD1306_CMD_SET_COL_ADDR            = 0x21,
    SSD1306_CMD_SET_PAGE_ADDR           = 0x22,
    SSD1306_CMD_SET_PAGE_START          = 0xB0,

    /* Hardware Configuration */
    SSD1306_CMD_SET_START_LINE          = 0x40,
    SSD1306_CMD_SET_SEG_REMAP_0         = 0xA0,
    SSD1306_CMD_SET_SEG_REMAP_1         = 0xA1,
    SSD1306_CMD_SET_MUX_RATIO           = 0xA8,
    SSD1306_CMD_SET_COM_SCAN_INC        = 0xC0,
    SSD1306_CMD_SET_COM_SCAN_DEC        = 0xC8,
    SSD1306_CMD_SET_DISPLAY_OFFSET      = 0xD3,
    SSD1306_CMD_SET_COM_PINS            = 0xDA,

    /* Timing & Driving */
    SSD1306_CMD_SET_DISPLAY_CLK_DIV     = 0xD5,
    SSD1306_CMD_SET_PRECHARGE           = 0xD9,
    SSD1306_CMD_SET_VCOMH_DESELECT      = 0xDB,
    SSD1306_CMD_NOP                     = 0xE3,

    /* Charge Pump */
    SSD1306_CMD_CHARGE_PUMP             = 0x8D,
} ssd1306_cmd_t;

/* Charge Pump (follows SSD1306_CMD_CHARGE_PUMP) */
typedef enum {
    SSD1306_CHARGE_PUMP_DISABLE = 0x10,
    SSD1306_CHARGE_PUMP_ENABLE  = 0x14,
} ssd1306_charge_pump_t;

/* Phase 1 period - lower nibble (follows SSD1306_CMD_SET_PRECHARGE) */
typedef enum {
    SSD1306_PRECHARGE_PHASE1_1  = 0x01,
    SSD1306_PRECHARGE_PHASE1_2  = 0x02,  /* reset */
    SSD1306_PRECHARGE_PHASE1_3  = 0x03,
    SSD1306_PRECHARGE_PHASE1_4  = 0x04,
    SSD1306_PRECHARGE_PHASE1_5  = 0x05,
    SSD1306_PRECHARGE_PHASE1_6  = 0x06,
    SSD1306_PRECHARGE_PHASE1_7  = 0x07,
    SSD1306_PRECHARGE_PHASE1_8  = 0x08,
    SSD1306_PRECHARGE_PHASE1_9  = 0x09,
    SSD1306_PRECHARGE_PHASE1_10 = 0x0A,
    SSD1306_PRECHARGE_PHASE1_11 = 0x0B,
    SSD1306_PRECHARGE_PHASE1_12 = 0x0C,
    SSD1306_PRECHARGE_PHASE1_13 = 0x0D,
    SSD1306_PRECHARGE_PHASE1_14 = 0x0E,
    SSD1306_PRECHARGE_PHASE1_15 = 0x0F,
} ssd1306_precharge_phase1_t;

/* Phase 2 period - upper nibble (follows SSD1306_CMD_SET_PRECHARGE) */
typedef enum {
    SSD1306_PRECHARGE_PHASE2_1  = 0x10,
    SSD1306_PRECHARGE_PHASE2_2  = 0x20,  /* reset */
    SSD1306_PRECHARGE_PHASE2_3  = 0x30,
    SSD1306_PRECHARGE_PHASE2_4  = 0x40,
    SSD1306_PRECHARGE_PHASE2_5  = 0x50,
    SSD1306_PRECHARGE_PHASE2_6  = 0x60,
    SSD1306_PRECHARGE_PHASE2_7  = 0x70,
    SSD1306_PRECHARGE_PHASE2_8  = 0x80,
    SSD1306_PRECHARGE_PHASE2_9  = 0x90,
    SSD1306_PRECHARGE_PHASE2_10 = 0xA0,
    SSD1306_PRECHARGE_PHASE2_11 = 0xB0,
    SSD1306_PRECHARGE_PHASE2_12 = 0xC0,
    SSD1306_PRECHARGE_PHASE2_13 = 0xD0,
    SSD1306_PRECHARGE_PHASE2_14 = 0xE0,
    SSD1306_PRECHARGE_PHASE2_15 = 0xF0,
} ssd1306_precharge_phase2_t;

/* VCOMH Deselect Level (follows SSD1306_CMD_SET_VCOMH_DESELECT) */
typedef enum {
    SSD1306_VCOMH_065_VCC = 0x00,
    SSD1306_VCOMH_077_VCC = 0x20,  /* reset */
    SSD1306_VCOMH_083_VCC = 0x30,
} ssd1306_vcomh_t;

/* Set Memory Addressing Mode (follows SSD1306_CMD_SET_MEM_ADDR_MODE) */
typedef enum {
    SSD1306_MEM_ADDR_HORIZONTAL = 0x00,
    SSD1306_MEM_ADDR_VERTICAL   = 0x01,
    SSD1306_MEM_ADDR_PAGE       = 0x02,
} ssd1306_mem_addr_mode_t;

/* COM Pins Hardware Configuration (follows SSD1306_CMD_SET_COM_PINS) */
typedef enum {
    SSD1306_COM_PINS_SEQUENTIAL         = 0x02,
    SSD1306_COM_PINS_ALTERNATIVE        = 0x12,  /* reset */
    SSD1306_COM_PINS_SEQUENTIAL_REMAP   = 0x22,
    SSD1306_COM_PINS_ALTERNATIVE_REMAP  = 0x32,
} ssd1306_com_pins_t;


#endif // !SSD1306_CMD_H
